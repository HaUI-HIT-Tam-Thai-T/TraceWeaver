"""Record installed Python package licenses separately from the npm inventory."""

import argparse
from importlib import metadata
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
AI = ROOT / "ai"


def normalize(name):
    return re.sub(r"[-_.]+", "-", name.lower())


def pins(filename):
    result = {}
    for line in filename.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, version = line.split("==")
        result[normalize(name)] = version
    return result


def generate():
    locked, direct = pins(AI / "requirements.txt"), pins(AI / "requirements.in")
    if any(locked.get(name) != version for name, version in direct.items()):
        raise ValueError("Direct dependencies and pinned requirements differ")
    installed = {normalize(dist.metadata["Name"]): dist for dist in metadata.distributions()
                 if normalize(dist.metadata["Name"]) not in {"pip", "setuptools", "wheel"}}
    if set(installed) != set(locked):
        raise ValueError("Use a dedicated virtual environment matching ai/requirements.txt")
    rows = []
    notices = ["Third-party Python package notices for ai/requirements.txt.\n"
               "Generated from installed wheel license files. Each package retains its own license.\n"]
    for name, version in sorted(locked.items()):
        dist = installed[name]
        if dist.version != version:
            raise ValueError(f"Installed version differs from requirements: {name}")
        license_name = dist.metadata.get("License-Expression") or dist.metadata.get("License")
        if name == "exceptiongroup":
            # Its bundled LICENSE includes both its MIT text and copied stdlib's PSF notice.
            license_name = "MIT AND PSF-2.0"
        if not license_name or "\n" in license_name:
            raise ValueError(f"Review upstream license metadata for {name}")
        license_files = sorted(str(file) for file in dist.files or []
                               if file.name.lower().startswith(("license", "copying", "notice")))
        if not license_files:
            raise ValueError(f"Missing bundled license text for {name}")
        texts = []
        for path in license_files:
            text = Path(dist.locate_file(path)).read_text(encoding="utf-8").replace("\r\n", "\n")
            texts.append(f"{path.split('.dist-info/', 1)[-1]}\n{text}")
        source = f"https://pypi.org/project/{name}/{version}/"
        rows.append(f"| {name} | {version} | {'direct' if name in direct else 'transitive'} | "
                    f"{license_name} | [PyPI]({source}) |")
        notices.append(f"\n{'=' * 72}\n{name}=={version} ({license_name})\n{source}\n\n" + "\n\n".join(texts))
    inventory = (
        "# AI Python dependencies\n\n"
        "Generated by `python -m ai.scripts.dependency_inventory` from the pinned packages installed "
        "in a dedicated virtual environment. Python 3.10 is the tested interpreter; Python has its "
        "own [license](https://docs.python.org/3/license.html).\n\n"
        "Project code uses [Apache-2.0](../LICENSE). Libraries retain the licenses below; full bundled "
        "texts are in [THIRD_PARTY_NOTICES.txt](THIRD_PARTY_NOTICES.txt). This records package license "
        "metadata/notices, not a security audit. The npm inventory does not cover these packages.\n\n"
        "No pretrained model or external dataset is installed in this baseline milestone.\n\n"
        "| Package | Version | Scope | License | Source |\n"
        "|---|---|---|---|---|\n" + "\n".join(rows) + "\n"
    )
    return {"DEPENDENCIES.md": inventory, "THIRD_PARTY_NOTICES.txt": "\n".join(notices).rstrip() + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in generate().items():
        path = AI / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Stale AI dependency inventory: {name}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print("AI Python license inventory " + ("verified." if args.check else "generated."))


if __name__ == "__main__":
    main()

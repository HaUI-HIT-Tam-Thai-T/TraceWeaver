import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const read = async (path) => (await readFile(resolve(root, path), 'utf8')).replace(/\r\n/g, '\n');
const lock = JSON.parse(await read('package-lock.json'));
const manifests = await Promise.all(['package.json', 'backend/package.json'].map(async (path) => JSON.parse(await read(path))));
const direct = new Set(manifests.flatMap((manifest) => Object.keys({ ...manifest.dependencies, ...manifest.devDependencies })));
const rows = [];
const notices = ['Third-party licenses for the exact npm dependency tree in package-lock.json.\nGenerated by npm run licenses. Each component retains its own license.\n'];

for (const [path, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (!path.startsWith('node_modules/') || entry.link) continue;
  const pkg = JSON.parse(await read(`${path}/package.json`));
  if (pkg.version !== entry.version || !entry.license || pkg.license !== entry.license) {
    throw new Error(`Installed package metadata differs from lockfile: ${path}`);
  }
  const names = (await readdir(resolve(root, path))).filter((name) => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name)).sort();
  const texts = [];
  for (const name of names) texts.push(`${name}\n${await read(`${path}/${name}`)}`);
  if (!texts.length) {
    const readme = await read(`${path}/README.md`);
    const index = readme.search(/^##?\s+licen[sc]e\s*$/im);
    if (index < 0) throw new Error(`Missing license text: ${pkg.name}`);
    texts.push(`README.md license section\n${readme.slice(index)}`);
  }
  rows.push(`| ${pkg.name} | ${entry.version} | ${entry.dev ? 'development' : 'runtime'} / ${direct.has(pkg.name) ? 'direct' : 'transitive'} | ${entry.license} | [npm](https://www.npmjs.com/package/${pkg.name}/v/${entry.version}) |`);
  notices.push(`\n${'='.repeat(72)}\n${pkg.name}@${entry.version} (${entry.license})\n${entry.resolved}\n${entry.integrity}\n\n${texts.join('\n\n')}`);
}

const inventory = `# Dependencies\n\nGenerated from package-lock.json by \`npm run licenses\`. Exact tarball URLs and integrity hashes are retained in the lockfile. Full upstream license/copyright notices are in [THIRD_PARTY_NOTICES.txt](THIRD_PARTY_NOTICES.txt).\n\nProject code: Apache-2.0. Third-party packages retain their original licenses. This inventory records license metadata and notices, not a security audit.\n\n## Runtime and services\n\n| Component | Version | Role | License/source |\n|---|---|---|---|\n| Node.js | 24.14.1 (engines >=24.14.1 <25) | Backend runtime | [Upstream license and bundled notices](https://github.com/nodejs/node/blob/v24.14.1/LICENSE) |\n| npm | 11.11.0 | Package manager | [Upstream](https://github.com/npm/cli/tree/v11.11.0) |\n| PostgreSQL | 17.11 | Development database | [PostgreSQL License](https://www.postgresql.org/about/licence/) |\n| PostgreSQL image | postgres:17-alpine@sha256:b0f9560a2de083e2cc7382e75f808c7381a32852a7ec49117deedb300e552b24 | Compose development | [Docker Official Image source](https://github.com/docker-library/postgres); image/base packages require a separate audit when distributing images |\n\nReact, Identity provider, AI runtime and model are not installed in this scaffold. Add their pinned versions, licenses and notices when implemented.\n\n## npm packages (${rows.length})\n\n| Package | Version | Scope | License | Source |\n|---|---|---|---|---|\n${rows.join('\n')}\n`;

for (const [path, text] of [['backend/DEPENDENCIES.md', inventory], ['backend/THIRD_PARTY_NOTICES.txt', notices.join('\n').trimEnd() + '\n']]) {
  if (process.argv.includes('--check')) {
    if (await read(path) !== text) throw new Error(`Stale inventory: ${path}; run npm run licenses`);
  } else await writeFile(resolve(root, path), text);
}
console.log(`License inventory ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${rows.length} npm packages.`);
